import http from 'node:http';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {serve} from '../client/src-tauri/sidecars/hyperframes-renderer/lib/server.mjs';
const projectDir=path.resolve('.tmp-ai-video-qa/project');
const {url}=await serve({projectDir});
const server=http.createServer(async(req,res)=>{res.setHeader('Access-Control-Allow-Origin','*');if(req.url==='/save'){let html='';for await(const chunk of req)html+=chunk;await fs.writeFile(path.join(projectDir,'index.html'),html);res.end('ok');}else res.end('ok');});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const host=`http://127.0.0.1:${server.address().port}`;
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:850}});
page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
await page.goto(`http://localhost:1420/qa-ai-video.html?preview=${encodeURIComponent(url)}&host=${encodeURIComponent(host)}`);
await page.getByRole('button',{name:'Text: Clippster',exact:true}).waitFor();
assert.equal(await page.getByRole('button',{name:/^Graphics:/}).count(),3);
assert.equal(await page.getByRole('button',{name:/^Text:/}).count(),4);
assert.equal(await page.getByRole('button',{name:/^Video:/}).count(),0);
assert.equal(await page.getByRole('button',{name:/Hide timeline|Edit timeline/}).count(),0);
for(const size of [{width:1440,height:850},{width:1100,height:680},{width:1000,height:600}]){
 await page.setViewportSize(size);await page.waitForTimeout(200);
 const dock=await page.getByRole('region',{name:'Video timeline'}).boundingBox();
 assert.ok(dock.y+dock.height<=size.height+1,'timeline stays on screen');
 assert.ok(dock.width>=size.width-1,'timeline spans full workspace');
}
await page.setViewportSize({width:1440,height:850});
await page.getByRole('button',{name:'Text: Clippster',exact:true}).click();
await page.getByRole('textbox',{name:'Text content'}).fill('New brand');
await page.waitForFunction(()=>window.lastEdit?.next.shots[2].scene.variables.wordmark==='New brand');
assert.equal(await page.evaluate(()=>window.lastEdit.next.shots[2].scene.variables.text),'Share your best');
await page.waitForTimeout(800);
await page.getByRole('button',{name:'Text: New brand',exact:true}).waitFor();
const ruler=page.getByRole('slider',{name:'Timeline ruler',exact:true});
const rect=await ruler.boundingBox();
await ruler.click({position:{x:(rect.width-24)*11/12,y:18}});
await page.waitForTimeout(300);
let sceneFrame=page.frames().find(f=>f!==page.mainFrame());
assert.ok(sceneFrame,'preview iframe exists');
await sceneFrame.waitForFunction(()=>document.querySelector('#share-word')?.textContent==='New brand');
await sceneFrame.waitForFunction(()=>getComputedStyle(document.querySelector('#shot-share-frame')).opacity==='1' && getComputedStyle(document.querySelector('#shot-share')).visibility==='visible');
console.log('PASS text lane edits correct wordmark and updates real preview');
await page.getByRole('button',{name:'Undo',exact:true}).click();
await page.getByRole('button',{name:'Text: Clippster',exact:true}).waitFor();
await page.frameLocator('iframe').locator('#share-word').filter({hasText:'Clippster'}).waitFor();
sceneFrame=page.frames().find(f=>f!==page.mainFrame());
await sceneFrame.waitForFunction(()=>document.querySelector('#share-word')?.textContent==='Clippster');
console.log('PASS text undo');
await page.getByRole('button',{name:'Zoom in',exact:true}).click();
await page.getByRole('button',{name:'Zoom to fit',exact:true}).click();
const finalRect=await ruler.boundingBox();
await ruler.click({position:{x:(finalRect.width-24)*11/12,y:18}});
await sceneFrame.waitForFunction(()=>getComputedStyle(document.querySelector('#shot-share-frame')).opacity==='1' && getComputedStyle(document.querySelector('#shot-share')).visibility==='visible');
const playhead=page.getByRole('slider',{name:'Timeline playhead',exact:true});
const head=await playhead.boundingBox();
await page.mouse.move(head.x+head.width/2,head.y+head.height/2);
await page.mouse.down();await page.mouse.move(finalRect.x+(finalRect.width-24)/2,head.y+head.height/2,{steps:5});await page.mouse.up();
assert.ok(Math.abs(Number(await ruler.getAttribute('aria-valuenow'))-6)<0.1,'drag playhead seeks to midpoint');
console.log('PASS draggable playhead');
await ruler.click({position:{x:(finalRect.width-24)*11/12,y:18}});
await page.waitForTimeout(200);
await page.screenshot({path:'.tmp-ai-video-qa/editor-timeline-fixed.png'});
console.log('PASS dock, responsive layout, lane classification, zoom');
await browser.close();server.close();process.exit(0);
