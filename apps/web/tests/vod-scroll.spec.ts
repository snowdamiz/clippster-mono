import { test, expect } from '@playwright/test'
test('VOD cards scroll within the page and pagination fills the panel footer', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 700 })
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill('test@example.com')
  await page.getByLabel('Password', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await page.route('**/api/web/account/media/vods?**', route => route.fulfill({ json: { success: true, has_more: true, vods: Array.from({ length: 19 }, (_, index) => ({ id: String(index), title: 'Archived VOD ' + index, duration_seconds: 26073, url: 'https://kick.com/fixture/videos/' + index })) } }))
  await page.goto('/?view=download&platform=kick&channel=fixture')
  await expect(page.locator('.vod-card')).toHaveCount(19)
  const content = page.locator('.page-layout__content')
  expect(await content.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await page.locator('.vod-card').last().scrollIntoViewIfNeeded()
  expect(await content.evaluate(element => element.scrollTop)).toBeGreaterThan(0)
  const last = await page.locator('.vod-card').last().boundingBox(), footer = await page.locator('footer').boundingBox(), layout = await page.locator('.page-layout').boundingBox()
  expect(last!.y + last!.height).toBeLessThanOrEqual(footer!.y + 1)
  expect(footer!.x).toBe(layout!.x)
  expect(footer!.width).toBe(layout!.width)
  await page.screenshot({ path: info.outputPath('vod-scroll-footer.png') })
})
