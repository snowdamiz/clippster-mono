import { test, expect } from './browser-fixture'

test('desktop branding dialogs upload, save and reopen account assets on web', async ({ page }, info) => {
  const profiles: Record<string, any>[] = []
  const image = Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="320" height="180"><rect width="320" height="180" fill="#00bfff"/></svg>')
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill('test@example.com')
  await page.getByLabel('Password', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Video library', exact: true })).toBeVisible()
  await page.route('**/api/web/account/user/creator-profiles*', async route => {
    const method = route.request().method()
    if (method === 'POST') profiles.push({ ...route.request().postDataJSON(), id: 1 })
    if (method === 'PUT') Object.assign(profiles[0], route.request().postDataJSON())
    await route.fulfill({ json: { success: true, profiles, profile: profiles[0] } })
  })
  await page.route('**/api/web/account/user/assigned-creator-profiles', route => route.fulfill({ json: { success: true, profiles: [] } }))
  await page.route('**/api/web/account/user/assets/*/content*', route => route.fulfill({ contentType: 'image/svg+xml', body: image }))
  const uploadImage = async (button: string) => {
    const chooser = page.waitForEvent('filechooser')
    await page.getByRole('button', { name: button, exact: true }).click()
    await (await chooser).setFiles({ name: 'branding.svg', mimeType: 'image/svg+xml', buffer: image })
  }
  await page.goto('/?view=creators')
  await page.locator('[data-tour-id=\"tour-add-creator\"]').click()
  await page.getByPlaceholder('Creator name').fill('Full branding creator')
  await expect(page.getByText('Auto DVR', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: 'Branding', exact: true }).click()
  await uploadImage('Upload new watermark')
  await expect(page.getByTitle('Configure watermark position', { exact: true })).toBeEnabled()
  await page.getByTitle('Configure watermark position', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Watermark position', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Watermark position', exact: true })).toHaveCount(0)
  await page.getByTitle('Configure intro per aspect ratio', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Intro videos per aspect ratio', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  await uploadImage('Upload overlay')
  await expect(page.getByTitle('Configure position per aspect ratio', { exact: true })).toBeEnabled()
  await page.getByTitle('Configure position per aspect ratio', { exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Overlay position', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('tab', { name: 'Clip defaults', exact: true }).click()
  await uploadImage('Upload screenshot')
  await expect(page.getByAltText('Reference frame preview')).toBeVisible()
  await page.getByRole('button', { name: /^(Configure|Edit)$/ }).click()
  await expect(page.getByRole('heading', { name: 'Creator clip defaults', exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('creator-framing-dialog.png') })
  await page.getByRole('dialog', { name: 'Creator clip defaults', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Creator clip defaults', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Profile', exact: true }).click()
  await expect(page.getByPlaceholder('Creator name')).toHaveValue('Full branding creator')
  await page.screenshot({ path: info.outputPath('creator-desktop-profile-dialog.png') })
  await page.getByRole('button', { name: 'Create profile', exact: true }).click()
  await expect(page.locator('article h3', { hasText: 'Full branding creator' })).toBeVisible()
  expect(profiles[0].watermark_id).toBeGreaterThan(0)
  expect(profiles[0].watermark_settings).toBeTruthy()
  expect(typeof profiles[0].intro_ratio_settings).toBe('string')
  expect(profiles[0].layout_overlays[0].assetId).toBeGreaterThan(0)
  expect(profiles[0].layout_overlays[0].imagePath).toBeUndefined()
  expect(profiles[0].clip_build_defaults.referenceImageAssetId).toBeGreaterThan(0)
  expect(profiles[0].clip_build_defaults.referenceImageUrl).toBeNull()
  await page.reload()
  await page.getByRole('article').getByTitle('More actions').click()
  await page.getByRole('menuitem', { name: 'Edit profile' }).click()
  await expect(page.getByPlaceholder('Creator name')).toHaveValue('Full branding creator')
  await page.getByRole('tab', { name: 'Clip defaults', exact: true }).click()
  await expect(page.getByAltText('Reference frame preview')).toBeVisible()
  await page.getByRole('tab', { name: 'Branding', exact: true }).click()
  await expect(page.getByTitle('Configure watermark position', { exact: true })).toBeEnabled()
  await expect(page.getByTitle('Configure position per aspect ratio', { exact: true })).toBeEnabled()
})
