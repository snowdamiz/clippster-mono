import { test, expect } from './browser-fixture'
test('Download Video opens the desktop search page and download options without a project-name step', async ({ page }, info) => {
  await page.goto('/')
  await page.getByLabel('Email', { exact: true }).fill('test@example.com')
  await page.getByLabel('Password', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: 'Sign In', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Video library', exact: true })).toBeVisible()
  expect((await page.request.delete('/api/web/vod-searches', { headers: { Origin: new URL(page.url()).origin } })).ok()).toBeTruthy()
  await page.reload()
  await page.getByRole('link', { name: 'Download Video', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Download video', exact: true })).toBeVisible()
  await expect(page.locator('.streamvods-platforms')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Recent', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Create Project', exact: true })).toHaveCount(0)
  const imports: Array<Record<string, unknown>> = []
  await page.route('**/api/web/account/media/vods?**', route => {
    const url = new URL(route.request().url())
    expect(url.searchParams.get('platform')).toBe('twitch')
    expect(url.searchParams.get('channel')).toBe('fixture-channel')
    return route.fulfill({ json: { success: true, vods: [{ id: 'test-vod', title: 'Desktop download flow', duration_seconds: 900, url: 'https://www.twitch.tv/videos/123', upload_date: '20261010' }] } })
  })
  await page.route('**/api/web/projects/*/import', route => { imports.push(route.request().postDataJSON()); return route.fulfill({ status: 202, json: { id: 'fixture-job', status: 'queued' } }) })
  await page.getByPlaceholder('Paste a stream link, mint ID or username…').fill('https://www.twitch.tv/fixture-channel')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  const card = page.getByRole('article').filter({ hasText: 'Desktop download flow' })
  await expect(card).toBeVisible()
  await expect(card).toContainText('15:00')
  await page.reload()
  await page.getByRole('link', { name: 'Download Video', exact: true }).click()
  await page.getByRole('button', { name: 'Recent', exact: true }).click()
  await page.getByRole('menuitem', { name: /fixture-channel/ }).click()
  await expect(card).toBeVisible()
  await page.screenshot({ path: info.outputPath('desktop-download-search.png') })
  await card.getByTitle('Download', { exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Download options', exact: true })
  await expect(dialog.getByText('Range', { exact: true })).toBeVisible()
  await expect(page.getByPlaceholder('Enter project name')).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('desktop-download-options.png') })
  await dialog.getByRole('button', { name: 'Start download', exact: true }).click()
  await expect.poll(() => imports.length).toBe(1)
  expect(imports[0]).toEqual({ url: 'https://www.twitch.tv/videos/123' })
  await expect(page.getByRole('heading', { name: 'Desktop download flow', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Project workspace', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Open workspace: Desktop download flow', exact: true })).toBeVisible()
  await page.route('**/workspace/api/**', async route => { const response = await route.fetch({ url: route.request().url().replace('/workspace/api/', '/api/') }); await route.fulfill({ response }) })
  await page.goto('/?embedded=1&view=download')
  await expect(page.getByRole('heading', { name: 'Download video', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Create Project', exact: true })).toHaveCount(0)
})
